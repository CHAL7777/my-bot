@router.callback_query(F.data == "admin_users_referrals")
async def users_referrals_callback(callback: types.CallbackQuery, is_admin: bool = False):
    """Show user referrals management"""
    if not is_admin:
        await callback.answer("Access denied", show_alert=True)
        return

    from app.repositories.referral_repo import ReferralRepository
    from sqlalchemy import desc

    async for session in get_db():
        referral_repo = ReferralRepository(session)
        
        # Get recent referrals
        from app.db.models import Referral, User
        query = select(Referral).order_by(desc(Referral.created_at)).limit(50)
        result = await session.execute(query)
        referrals = result.scalars().all()

    text = "🔗 *User Referrals*\n\n"
    
    if referrals:
        for referral in referrals[:10]:
            status_emoji = "✅" if referral.status == 'completed' else "⏳" if referral.status == 'pending' else "❌"
            text += f"{status_emoji} Referral {referral.id}: {referral.referrer_id} → {referral.referred_id} ({referral.status})\n"
        
        if len(referrals) > 10:
            text += f"\n... and {len(referrals) - 10} more"
    else:
        text += "No referrals yet."

    await callback.message.edit_text(
        text,
        parse_mode='Markdown',
        reply_markup=AdminManageKeyboard.get_back_to_admin_keyboard()
    )
    await callback.answer()

