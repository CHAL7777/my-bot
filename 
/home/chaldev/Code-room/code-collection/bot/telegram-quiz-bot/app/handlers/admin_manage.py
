@router.message(Command("add_admin"))
async def add_admin_command(message: types.Message, is_superadmin: bool = False,
                           admin_role: str = None):
    """Add a new admin - Super Admin only"""
    user_id = message.from_user.id
    parts = message.text.split()

    if not is_superadmin:
        await message.answer("❌ Access denied. Super Admin only.", parse_mode='Markdown')
        return

    if len(parts) < 2:
        await message.answer("Usage: /add_admin <user_id> [role]", parse_mode='Markdown')
        return

    try:
        target_user_id = int(parts[1])
    except ValueError:
        await message.answer("Invalid user ID", parse_mode='Markdown')
        return

    role = 'admin'
    if len(parts) >= 3 and parts[2].lower() in ['admin', 'superadmin']:
        role = parts[2].lower()

    async for session in get_db():
        admin_repo = TelegramAdminRepository(session)
        user_repo = UserRepository(session)
        log_repo = AdminLogRepository(session)

        target_user = await user_repo.get_user(target_user_id)
        if not target_user:
            await message.answer(f"User {target_user_id} not found", parse_mode='Markdown')
            return

        existing = await admin_repo.get_admin(target_user_id)
        if existing and existing.is_active:
            await message.answer(f"User is already an admin", parse_mode='Markdown')
            return

        username = target_user.username
        await admin_repo.create_admin(target_user_id, username, role, user_id)
        await log_repo.log_action(user_id, "Add Admin", f"Added {username} as {role}")

    await message.answer(f"✅ Admin added: @{username} as {role}", parse_mode='Markdown')


@router.message(Command("remove_admin"))
async def remove_admin_command(message: types.Message, is_superadmin: bool = False):
    """Remove an admin - Super Admin only"""
    user_id = message.from_user.id
    parts = message.text.split()

    if not is_superadmin:
        await message.answer("❌ Access denied. Super Admin only.", parse_mode='Markdown')
        return

    if len(parts) < 2:
        await message.answer("Usage: /remove_admin <user_id>", parse_mode='Markdown')
        return

    try:
        target_user_id = int(parts[1])
    except ValueError:
        await message.answer("Invalid user ID", parse_mode='Markdown')
        return

    if target_user_id == user_id:
        await message.answer("Cannot remove yourself", parse_mode='Markdown')
        return

    async for session in get_db():
        admin_repo = TelegramAdminRepository(session)
        user_repo = UserRepository(session)
        log_repo = AdminLogRepository(session)

        admin = await admin_repo.get_admin(target_user_id)
        if not admin:
            await message.answer("User is not an admin", parse_mode='Markdown')
            return

        target_user = await user_repo.get_user(target_user_id)
        username = target_user.username if target_user else None

        await admin_repo.remove_admin(target_user_id)
        await log_repo.log_action(user_id, "Remove Admin", f"Removed {username}")

    await message.answer(f"✅ Admin removed: @{username}", parse_mode='Markdown')


